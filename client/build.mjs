import { build } from "esbuild";
import { writeFileSync, renameSync, readFileSync } from "node:fs";
import path from "node:path";
const output = path.join(import.meta.dirname, "public/app.js");
const themeOutput = path.join(import.meta.dirname, "public/theme.css");
const theme = readFileSync(path.join(import.meta.dirname, "src/theme.css"));
const result = await build({
  entryPoints: [path.join(import.meta.dirname, "src/app.js")],
  bundle: true,
  define: { "process.env.NODE_ENV": '"production"' },
  // Semi's package exports omit its bundled stylesheet; keep it inside the React island.
  alias: {
    "@douyinfe/semi-ui/dist/css/semi.min.css": path.join(
      import.meta.dirname,
      "node_modules/@douyinfe/semi-ui/dist/css/semi.min.css",
    ),
  },
  loader: { ".webp": "dataurl", ".png": "dataurl", ".css": "text" },
  format: "esm",
  target: "es2022",
  minify: true,
  legalComments: "eof",
  write: false,
  banner: { js: "// Generated by npm run build. Edit client/src/, not this file." },
});
if (process.argv.includes("--check")) {
  if (!readFileSync(themeOutput).equals(theme))
    throw new Error("Theme stylesheet is stale. Run npm run build in client/.");
  if (!readFileSync(output).equals(Buffer.from(result.outputFiles[0].contents)))
    throw new Error("Browser bundle is stale. Run npm run build in client/.");
  console.log("Browser bundle matches source.");
} else {
  writeFileSync(themeOutput + ".tmp", theme);
  renameSync(themeOutput + ".tmp", themeOutput);
  writeFileSync(output + ".tmp", result.outputFiles[0].contents);
  renameSync(output + ".tmp", output);
  console.log("Built local workbench client (" + Math.round(result.outputFiles[0].contents.length / 1024) + " KB)");
}
